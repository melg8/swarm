# Regenerate the npc combat and adena table of the bot from the Mobius C1
# npc stats. The hunt prices a hunting ground by the adena its mobs pay per
# second of work: the hp drives the fight time at the measured damage rate,
# the physical attack drives the incoming damage and the drop list carries
# the mean adena per kill (the group chance times the amount range). The
# level gap scale of the adena drop is applied by the caller (Rates.ini
# DropAdena*), so the table stays the raw template values.
#
#   npc: xml template id -> level, hp, pAtk, pDef, exp, mean adena
#        via dist/game/data/stats/npcs/*.xml
#
# Usage: tools/generate_npc_combat.sh [path/to/L2J_Mobius_C1_HarbingersOfWar]
# Output: internal/swarm/npcdata/npc_combat_table.go

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SWARM_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
MOBIUS_C1="${1:-$(dirname "${SWARM_ROOT}")/l2j_mobius/L2J_Mobius_C1_HarbingersOfWar}"
OUT="${SCRIPT_DIR}/../internal/swarm/npcdata/npc_combat_table.go"

STATS="${MOBIUS_C1}/dist/game/data/stats"
[ -d "${STATS}/npcs" ] || {
    echo "Error mobius npc stats not found at ${STATS}/npcs"
    echo "Usage: $0 [path/to/L2J_Mobius_C1_HarbingersOfWar]"
    exit 1
}

mkdir -p "$(dirname "${OUT}")"

python3 - "${STATS}/npcs" "${OUT}" << 'PYEOF'
import glob
import os
import re
import sys

npc_dir, out = sys.argv[1], sys.argv[2]

# The npc element order varies: the level, the type and the name live in the
# opening tag, the body carries the vitals, the attack, the defence, the
# experience and the drop lists.
npc_pattern = re.compile(r'<npc\s+id="(\d+)"([^>]*)>(.*?)</npc>', re.S)
attr_pattern = re.compile(r'(\w+)="([^"]*)"')
hp_pattern = re.compile(r'hp="([\d.]+)"')
patk_pattern = re.compile(r'<attack\s+physical="([\d.]+)"')
pdef_pattern = re.compile(r'<defence\s+physical="([\d.]+)"')
exp_pattern = re.compile(r'<acquire\s+exp="(\d+)"')
# The adena group of the drop list: the group chance gates the whole group,
# the item chance is the relative chance inside it and the amount range the
# roll. The spoil list never pays on a plain kill.
adena_pattern = re.compile(
    r'<group\s+chance="([\d.]+)"[^>]*>\s*'
    r'<item\s+id="57"\s+min="(\d+)"\s+max="(\d+)"\s+chance="([\d.]+)"')

rows = []
for path in sorted(glob.glob(os.path.join(npc_dir, '*.xml'))):
    with open(path, encoding='utf-8', errors='replace') as handle:
        source = handle.read()
    for match in npc_pattern.finditer(source):
        template_id = int(match.group(1))
        attrs = dict(attr_pattern.findall(match.group(2)))
        body = match.group(3)
        level = attrs.get('level')
        hp = hp_pattern.search(body)
        patk = patk_pattern.search(body)
        pdef = pdef_pattern.search(body)
        if level is None or hp is None or patk is None or pdef is None:
            continue
        exp = exp_pattern.search(body)
        drop = body.split('<spoil>')[0]
        adena = 0.0
        adena_match = adena_pattern.search(drop)
        if adena_match:
            group, low, high, chance = adena_match.groups()
            adena = (float(group) / 100.0 * float(chance) / 100.0 *
                     (float(low) + float(high)) / 2.0)
        rows.append((
            template_id,
            int(level),
            float(hp.group(1)),
            float(patk.group(1)),
            float(pdef.group(1)),
            int(exp.group(1)) if exp else 0,
            adena,
        ))

rows.sort(key=lambda row: row[0])
if not rows:
    sys.exit('Error no npc template parsed from ' + npc_dir)

with open(out, 'w', encoding='utf-8', newline='\n') as handle:
    handle.write(
        '// SPDX-FileCopyrightText: 2026 Melg Eight '
        '<public.melg8@gmail.com>\n'
        '//\n'
        '// SPDX-License-Identifier: MIT\n'
        '\n'
        '// Code generated by tools/generate_npc_combat.sh from the\n'
        '// Mobius C1 npc stats; DO NOT EDIT by hand - re-run the\n'
        '// generator instead.\n'
        '\n'
        'package npcdata\n'
        '\n'
        '// npcCombatTable is the combat profile of every npc template,\n'
        '// sorted by template id (NPCCombatProfile binary searches it).\n'
        'var npcCombatTable = [...]NPCCombat{\n')
    for row in rows:
        handle.write(
            '    {TemplateID: %d, Level: %d, HP: %.4f, PAtk: %g, '
            'PDef: %g, Exp: %d, Adena: %.2f},\n' % row)
    handle.write('}\n')

print('wrote %d npc combat rows to %s' % (len(rows), out))
PYEOF
