// TestRepoLogConventions pins the AGENTS.md logging conventions at
// every production log call site of the module: the scan of the whole
// tree must come back empty. A new violation means the message needs
// a capital first letter (a lowercase component tag like
// "login#%d:" or "hunt audit:" is a valid start too) and no trailing
// period - fix the message, not the checker; the checker exists so
// the convention survives without a reviewer in the loop.
func TestRepoLogConventions(t *testing.T) {
    violations, err := ScanTree("../..")
    require.NoError(t, err)
    for _, violation := range violations {
        t.Errorf("%s:%d %s: %q",
            violation.File, violation.Line,
            violation.Rule, violation.Message)
    }
}
