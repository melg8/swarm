// metricsPath is the destination of the soak trail the M1 acceptance names: one
// JSON line per run, rendered into the progress report by
// tools/progress_report.sh. The file is created on the first append.
func metricsPath() string {
    return filepath.Join(metricsDir(), "metrics.jsonl")
}

// metricsDir resolves the runs directory: SWARM_RUNS_DIR redirects the trail,
// the default is the "runs" directory at the repository root.
func metricsDir() string {
    if dir := os.Getenv("SWARM_RUNS_DIR"); dir != "" {
        return dir
    }

    return filepath.Join(repoRoot(), "runs")
}

// repoRoot walks up from the working directory to the repository root (the
// directory that holds AGENTS.md), so a go test run from any directory lands in
// the same runs/.
func repoRoot() string {
    dir, err := filepath.Abs(".")
    if err != nil {
        return "."
    }
    for range 8 {
        if _, err := os.Stat(
            filepath.Join(dir, "AGENTS.md")); err == nil {
            return dir
        }
        parent := filepath.Dir(dir)
        if parent == dir {
            break
        }
        dir = parent
    }

    return dir
}

// soakMetrics is one row of runs/metrics.jsonl: the fields the M1 acceptance
// and the progress report read, with stable JSON tags.
type soakMetrics struct {
    Date        string  `json:"date"`
    Scenario    string  `json:"scenario"`
    DurationSec int64   `json:"durationSec"`
    StartLevel  int32   `json:"startLevel"`
    EndLevel    int32   `json:"endLevel"`
    XpPerHour   float64 `json:"xpPerHour"`
    Deaths      int     `json:"deaths"`
    Adena       int32   `json:"adena"`
    StuckEvents int     `json:"stuckEvents"`
    Status      string  `json:"status"`
    FailReason  string  `json:"failReason,omitempty"`
}

// appendMetrics writes one JSON line to the metrics trail. O_APPEND keeps
// concurrent runs from interleaving, and one Marshal plus one Write keeps the
// line atomic.
func appendMetrics(path string, row soakMetrics) error {
    payload, err := json.Marshal(row)
    if err != nil {
        return fmt.Errorf("marshal metrics: %w", err)
    }
    payload = append(payload, '\n')
    if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
        return fmt.Errorf("create metrics dir: %w", err)
    }
    file, err := os.OpenFile(path,
        os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
    if err != nil {
        return fmt.Errorf("open metrics: %w", err)
    }
    defer func() {
        _ = file.Close()
    }()
    if _, err := file.Write(payload); err != nil {
        return fmt.Errorf("write metrics: %w", err)
    }

    return nil
}

// xpPerHour computes the hourly experience rate from the cumulative delta and
// the run duration; a non-positive duration answers zero.
func xpPerHour(startCum, endCum int64, duration time.Duration) float64 {
    if duration <= 0 {
        return 0
    }
    delta := endCum - startCum
    if delta < 0 {
        delta = 0
    }

    return float64(delta) / duration.Hours()
}

