// cumulativeSoakXP returns the total experience the character accumulated. The
// tracker exp already is that total (PlayableStat.addExp keeps one running
// number and UserInfo.writeImpl broadcasts it), so adding the level start
// threshold would double count it and inflate every xpPerHour row. The level
// stays in the signature for the callers that read it alongside, and a tracker
// that has not seen a UserInfo yet answers its raw exp.
func cumulativeSoakXP(level int32, exp int32) int64 {
    if level < 1 {
        return int64(exp)
    }

    return int64(exp)
}
